/// Distance of `got` from `want` in ulps of `want` (subnormal spacing below
/// the normals); equal infinities are 0 apart.
fn ulps(got: f64, want: f64) -> f64 {
    if got == want {
        return 0.0;
    }
    if !got.is_finite() || !want.is_finite() {
        return f64::INFINITY;
    }
    let u = (f64::from_bits(want.abs().to_bits() + 1) - want.abs()).max(f64::from_bits(1));
    (got - want).abs() / u
}

/// Powers from the fourth up are correctly rounded; a cube is two
/// multiplications, and a negative power 1/xⁿ, one rounding more
/// (`functions::pow_int` says why).
#[test]
fn integer_powers_are_correctly_rounded() {
    let mut bad = Vec::new();
    for &(x, n, want) in CASES {
        let got = pow_int(x, n);
        let allowed = match n {
            3 | -3 => 2.0,
            4.. => 0.0,
            _ => 1.0,
        };
        if ulps(got, want) > allowed {
            bad.push(format!("{x:e}^{n} = {got:e}, exact {want:e}"));
        }
    }
    assert!(bad.is_empty(), "{} off:\n{}", bad.len(), bad.join("\n"));
}

/// The compiler's integer power (a constant exponent) is the same function.
#[test]
fn compiled_integer_powers_match() {
    for n in [3, 5, 7, 31, -3] {
        let p = compile_str(&format!("x^({n})"), TrigUnit::Radians).unwrap();
        for &(x, m, _) in CASES {
            if m == n {
                let (got, want) = (p.eval(x, 0.0), pow_int(x, n));
                assert!(
                    got.to_bits() == want.to_bits(),
                    "x^{n} at {x:e}: {got:e} vs {want:e}"
                );
            }
        }
    }
}

/// a/xⁿ is compiled as a·x⁻ⁿ; with a = 1 that is bit for bit the division.
#[test]
fn reciprocal_powers_are_the_division() {
    for n in [2, 3, 5] {
        let p = compile_str(&format!("1/x^{n}"), TrigUnit::Radians).unwrap();
        for &(x, _, _) in CASES {
            let (got, want) = (p.eval(x, 0.0), 1.0 / pow_int(x, n));
            assert!(
                got.to_bits() == want.to_bits() || (got.is_nan() && want.is_nan()),
                "1/x^{n} at {x:e}: {got:e} vs {want:e}"
            );
        }
    }
}
