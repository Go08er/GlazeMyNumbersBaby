fn eval(name: &str, u: TrigUnit, x: f64) -> f64 {
    match name {
        "sin" => fns::sin_u(x, u),
        "cos" => fns::cos_u(x, u),
        "tan" => fns::tan_u(x, u),
        "sec" => fns::sec_u(x, u),
        "csc" => fns::csc_u(x, u),
        "cot" => fns::cot_u(x, u),
        "asin" => fns::asin_u(x, u),
        "acos" => fns::acos_u(x, u),
        "atan" => fns::atan_u(x, u),
        "asec" => fns::asec_u(x, u),
        "acsc" => fns::acsc_u(x, u),
        "acot" => fns::acot_u(x, u),
        "sinh" => x.sinh(),
        "cosh" => x.cosh(),
        "tanh" => x.tanh(),
        "sech" => fns::sech(x),
        "csch" => fns::csch(x),
        "coth" => fns::coth(x),
        "asinh" => x.asinh(),
        "acosh" => x.acosh(),
        "atanh" => fns::atanh(x),
        "asech" => fns::asech(x),
        "acsch" => fns::acsch(x),
        "acoth" => fns::acoth(x),
        "ln" => fns::ln(x),
        "log10" => fns::log10(x),
        "gamma" => fns::gamma(x),
        _ => {
            // pow_P_Q: x^(P/Q) with real roots, `m` for a minus sign.
            let mut it = name.strip_prefix("pow_").expect(name).split('_');
            let mut int = || -> i32 { it.next().unwrap().replace('m', "-").parse().unwrap() };
            let (p, q) = (int(), int());
            fns::pow_rational(x, p, q)
        }
    }
}

/// Distance in ulps of `want` (subnormal spacing below the normals); both
/// NaN, or both the same infinity, is 0.
fn ulps(got: f64, want: f64) -> f64 {
    if want.is_nan() || got.is_nan() {
        return if want.is_nan() && got.is_nan() {
            0.0
        } else {
            f64::INFINITY
        };
    }
    if want.is_infinite() || got.is_infinite() {
        return if got == want { 0.0 } else { f64::INFINITY };
    }
    if got == want {
        return 0.0;
    }
    let u = (f64::from_bits(want.abs().to_bits() + 1) - want.abs()).max(f64::from_bits(1));
    (got - want).abs() / u
}

/// Allowed error, in ulps, by function: libm's own (about 1) and a few
/// roundings of our own, plus the conversion to degrees or grads where
/// there is one. Γ's Lanczos sum (g = 7, nine terms) is good to about
/// 2·10⁻¹³ relative near its overflow (Γ(170.5) is 726 ulps off), far
/// below the 6 digits anything shows.
fn allowed(name: &str, u: TrigUnit) -> f64 {
    let conv = if u == Radians { 0.0 } else { 2.0 };
    match name {
        "gamma" => 1024.0,
        "sinh" | "cosh" | "tanh" | "asinh" | "acosh" | "atanh" | "ln" | "log10" => 2.0,
        _ => 4.0 + conv,
    }
}

#[test]
fn functions_hold_their_exact_values_at_extreme_arguments() {
    let mut worst: std::collections::BTreeMap<(String, String), (f64, f64, f64, f64)> =
        Default::default();
    let mut bad = Vec::new();
    for &(name, u, x, want) in CASES {
        let got = eval(name, u, x);
        let e = ulps(got, want);
        let key = (name.to_string(), format!("{u:?}"));
        let w = worst.entry(key).or_insert((0.0, 0.0, 0.0, 0.0));
        if e > w.0 {
            *w = (e, x, got, want);
        }
        if e > allowed(name, u) {
            bad.push(format!(
                "{name}({x:e}) [{u:?}] = {got:e}, exact {want:e}: {e:.3e} ulps"
            ));
        }
    }
    if std::env::var_os("SHOW_WORST").is_some() {
        for ((n, u), (e, x, g, w)) in &worst {
            eprintln!("{n:6} {u:8} worst {e:10.3e} ulps at {x:e}: {g:e} vs {w:e}");
        }
    }
    assert!(
        bad.is_empty(),
        "{} beyond tolerance:\n{}",
        bad.len(),
        bad.join("\n")
    );
}
