thread_local! {
    static CTX: RefCell<Ctx> = RefCell::new(Ctx::initial());
}

/// Runs `f` with shared access to this thread's ratpak globals.
pub(crate) fn with_ctx<R>(f: impl FnOnce(&Ctx) -> R) -> R {
    CTX.with(|c| f(&c.borrow()))
}

/// Runs `f` with exclusive access to this thread's ratpak globals.
pub(crate) fn with_ctx_mut<R>(f: impl FnOnce(&mut Ctx) -> R) -> R {
    CTX.with(|c| f(&mut c.borrow_mut()))
}
