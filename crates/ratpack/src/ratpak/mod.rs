/// `LOGNUMRADIX(pnum)`
#[inline]
pub(crate) fn lognumradix(ctx: &Ctx, pnum: &Number) -> i32 {
    pnum.cdigit()
        .wrapping_add(pnum.exp)
        .wrapping_mul(ctx.g_ratio)
}

/// `LOGRATRADIX(prat)`
#[inline]
pub(crate) fn logratradix(ctx: &Ctx, prat: &Rat) -> i32 {
    lognumradix(ctx, &prat.pp).wrapping_sub(lognumradix(ctx, &prat.pq))
}

/// `LOGNUM2(pnum)`
#[inline]
pub(crate) fn lognum2(pnum: &Number) -> i32 {
    pnum.cdigit().wrapping_add(pnum.exp)
}

/// `LOGRAT2(prat)`
#[inline]
pub(crate) fn lograt2(prat: &Rat) -> i32 {
    lognum2(&prat.pp).wrapping_sub(lognum2(&prat.pq))
}

/// `SIGN(prat)`
#[inline]
pub(crate) fn sign(prat: &Rat) -> i32 {
    prat.pp.sign.wrapping_mul(prat.pq.sign)
}

/// `ABSRAT(x)`
#[inline]
pub(crate) fn absrat(x: &mut Rat) {
    x.pp.sign = 1;
    x.pq.sign = 1;
}

/// `RENORMALIZE(x)`, gets the exponents non-negative.
#[inline]
pub(crate) fn renormalize(x: &mut Rat) {
    if x.pp.exp < 0 {
        x.pq.exp = x.pq.exp.wrapping_sub(x.pp.exp);
        x.pp.exp = 0;
    }
    if x.pq.exp < 0 {
        x.pp.exp = x.pp.exp.wrapping_sub(x.pq.exp);
        x.pq.exp = 0;
    }
}

/// Drops the `trim` least significant digits (the `memmove` in the TRIM
/// macros). Clamped so a malformed input cannot index out of bounds where the
/// C++ would read out of bounds.
#[inline]
pub(crate) fn drop_low_digits(x: &mut Number, trim: usize) {
    let trim = trim.min(x.mant.len());
    x.mant.drain(..trim);
}

/// `TRIMNUM(x, precision)`. ASSUMES the number is in radix form NOT INTERNAL BASEX!!!
#[inline]
pub(crate) fn trimnum(ctx: &Ctx, x: &mut Number, precision: i32) {
    if !ctx.g_ftrueinfinite {
        let trim = x.cdigit().wrapping_sub(precision).wrapping_sub(ctx.g_ratio);
        if trim > 1 {
            drop_low_digits(x, trim as usize);
            x.exp = x.exp.wrapping_add(trim);
        }
    }
}

/// `TRIMTOP(x, precision)`. ASSUMES the number is in INTERNAL BASEX!!!
#[inline]
pub(crate) fn trimtop(ctx: &Ctx, x: &mut Rat, precision: i32) {
    if !ctx.g_ftrueinfinite {
        let mut trim =
            x.pp.cdigit()
                .wrapping_sub(precision / ctx.g_ratio)
                .wrapping_sub(2);
        if trim > 1 {
            drop_low_digits(&mut x.pp, trim as usize);
            x.pp.exp = x.pp.exp.wrapping_add(trim);
        }
        trim = x.pp.exp.min(x.pq.exp);
        x.pp.exp = x.pp.exp.wrapping_sub(trim);
        x.pq.exp = x.pq.exp.wrapping_sub(trim);
    }
}

/// `SMALL_ENOUGH_RAT(a, precision)`
#[inline]
pub(crate) fn small_enough_rat(ctx: &Ctx, a: &Rat, precision: i32) -> bool {
    num::zernum(&a.pp)
        || (a.pq.cdigit().wrapping_add(a.pq.exp))
            .wrapping_sub(a.pp.cdigit().wrapping_add(a.pp.exp))
            .wrapping_sub(1)
            .wrapping_mul(ctx.g_ratio)
            > precision
}

/// `INC(a)`: the rational equivalent of `a++`.
#[inline]
pub(crate) fn inc(ctx: &Ctx, a: &mut Number) -> CalcResult<()> {
    if a.d0() < BASEX - 1 {
        a.mant[0] += 1;
        Ok(())
    } else {
        num::addnum(a, &ctx.num_one, BASEX)
    }
}

/// `CREATETAYLOR()` minus the `thisterm`/`n2` declarations: returns
/// `(xx, pret)` where `xx = x*x` and `pret = 0/0`.
pub(crate) fn create_taylor(ctx: &Ctx, px: &Rat, precision: i32) -> CalcResult<(Rat, Rat)> {
    let mut xx = px.clone();
    rat::mulrat(ctx, &mut xx, px, precision)?;
    Ok((xx, zero_over_zero()))
}

/// The `pret` set up by `CREATETAYLOR()`: `i32tonum(0)/i32tonum(0)`.
pub(crate) fn zero_over_zero() -> Rat {
    Rat {
        pp: conv::i32tonum(0, BASEX),
        pq: conv::i32tonum(0, BASEX),
    }
}

/// `DESTROYTAYLOR()`: `trimit(&pret); *px = pret`.
pub(crate) fn destroy_taylor(ctx: &Ctx, px: &mut Rat, mut pret: Rat, precision: i32) {
    support::trimit(ctx, &mut pret, precision);
    *px = pret;
}

