use std::cell::RefCell;

pub(crate) use crate::{CalcResult, Number};

/// Internal log2(BASEX)
pub(crate) const BASEXPWR: u32 = 31;
/// Internal radix used in calculations.
pub(crate) const BASEX: u32 = 0x8000_0000;
/// Base 2 requires 32 'digits'
pub(crate) const MAX_LONG_SIZE: u32 = 33;

/// `RAT`: `pp / pq`, where `pp` and `pq` are integral `NUMBER`s.
#[derive(Clone, Debug)]
pub(crate) struct Rat {
    pub pp: Number,
    pub pq: Number,
}

impl Number {
    /// `cdigit`
    #[inline]
    pub(crate) fn cdigit(&self) -> i32 {
        self.mant.len() as i32
    }

    /// `mant[0]`. C++ reads `mant[0]` unconditionally even when
    /// `cdigit == 0`; the slot is always a calloc'd zero in that case.
    #[inline]
    pub(crate) fn d0(&self) -> u32 {
        self.mant.first().copied().unwrap_or(0)
    }

    /// `MSD(x)`: `mant[cdigit - 1]`.
    #[inline]
    pub(crate) fn msd(&self) -> u32 {
        self.mant.last().copied().unwrap_or(0)
    }
}

