//! Port of `Ratpack` (`ratpak.h`): the infinite precision rational package.
//!
//! The C++ `NUMBER` struct (`sign`, `cdigit`, `exp`, `mant[]`) is represented
//! by [`crate::Number`], with `cdigit == mant.len()`. A `RAT` (`pp`/`pq`) is
//! [`Rat`]. The C++ functions that take `PNUMBER*`/`PRAT*` out-parameters
//! take `&mut` here, and everything that can `throw` returns [`CalcResult`].
//!
//! The process globals of ratpak (`g_ratio`, `g_ftrueinfinite`, the decimal
//! separator, `cbitsofprecision` and every `num_*`/`rat_*` constant) live in
//! the single [`Ctx`] struct, held in a thread-local and passed down
//! explicitly as `&Ctx`.
//!
//! Integer arithmetic on exponents, digit counts and precisions uses
//! two's-complement wrapping where the C++ could overflow (MSVC wraps; the
//! differential oracle is compiled with `-fwrapv`).

